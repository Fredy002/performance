export function localizeServiceMessage(locale: 'es' | 'en', message: string): string {
  if (locale === 'es') return message;
  if ((Object.values(en) as string[]).includes(message)) return message;
  const key = (Object.keys(es) as (keyof typeof es)[]).find((candidate) => es[candidate] === message);
  return key ? en[key] : en['service.error.generic'];
}
